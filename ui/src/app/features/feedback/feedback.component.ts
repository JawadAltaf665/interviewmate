import { Component, computed, inject, OnInit, signal } from '@angular/core';
import { DatePipe } from '@angular/common';
import { ActivatedRoute, RouterLink } from '@angular/router';
import { BridgeService } from '../../core/bridge.service';
import { CoachService } from '../../core/coach.service';
import { localFeedback } from '../../core/feedback-local';
import { Feedback, InterviewLanguage, SessionRecord, TranscriptEntry } from '../../core/interviewmate-api';
import { SessionStateService } from '../../core/session-state.service';

type FeedbackSource = 'gemini' | 'local';

@Component({
  selector: 'app-feedback',
  standalone: true,
  imports: [RouterLink, DatePipe],
  templateUrl: './feedback.component.html',
  styleUrl: './feedback.component.scss',
})
export class FeedbackComponent implements OnInit {
  private readonly state = inject(SessionStateService);
  private readonly bridge = inject(BridgeService);
  private readonly route = inject(ActivatedRoute);
  protected readonly coach = inject(CoachService);

  readonly session = signal<SessionRecord | null>(null);
  readonly feedback = signal<Feedback | null>(null);
  readonly source = signal<FeedbackSource>('local');
  readonly credentialName = signal('');
  readonly sourceNote = signal('');
  readonly loading = signal(false);
  readonly saved = signal(false);
  readonly saveError = signal('');
  // Transcript language view: the raw (possibly mixed) transcript or a translation.
  readonly transcriptView = signal<'original' | InterviewLanguage>('original');
  readonly translations = signal<Partial<Record<InterviewLanguage, TranscriptEntry[]>>>({});
  readonly translating = signal(false);
  readonly translateError = signal('');
  // Saved interviews: kept until the user removes one.
  readonly history = signal<SessionRecord[]>([]);
  readonly pastSessions = computed(() => this.history().filter((s) => s.id !== this.session()?.id));
  readonly pendingRemove = signal<string | null>(null);
  readonly historyError = signal('');
  /** Saved interview to expand (?open=<id>, used by the Coach). */
  readonly openId = signal<string | null>(null);

  async ngOnInit(): Promise<void> {
    this.route.queryParamMap.subscribe((q) => {
      this.openId.set(q.get('open'));
      if (this.openId()) setTimeout(() => this.scrollToOpen());
    });
    void this.loadHistory().then(() => this.scrollToOpen());
    const session = this.state.lastSession();
    this.session.set(session);
    if (!session) return;
    this.loading.set(true);
    const config = this.state.config();
    const target = config?.transcriptLanguage ?? 'English';
    // Urdu speech is usually code-switched, so translate whenever Urdu is involved.
    if (session.transcript.length && (target === 'Urdu' || config?.language === 'Urdu')) {
      void this.showTranscriptIn(target);
    }
    try {
      const result = await this.bridge.generateFeedback({
        transcript: session.transcript,
        level: session.level,
        cvSummary: config?.cvSummary ?? null,
        language: target,
      });
      this.feedback.set(result.feedback);
      this.source.set('gemini');
      this.credentialName.set(result.credentialName);
      this.sourceNote.set(`Generated by Gemini using your "${result.credentialName}" credential, from the actual transcript of this session.` +
        (result.fellBack ? ` Your selected model was out of quota or overloaded, so ${result.model} was used instead.` : ''));
    } catch (err) {
      // No key, quota, or desktop unavailable → honest local fallback.
      this.feedback.set(localFeedback(session.transcript, config?.cvSummary ?? null));
      this.source.set('local');
      this.sourceNote.set(
        `Gemini feedback was unavailable (${err instanceof Error ? err.message : 'unknown error'}), so this is local heuristic feedback computed on your device from the transcript text. It cannot judge technical accuracy.`,
      );
    } finally {
      this.loading.set(false);
    }
  }

  async save(): Promise<void> {
    if (!this.session() || this.saved()) return;
    this.saveError.set('');
    try {
      await this.persist();
      this.saved.set(true);
    } catch (err) {
      this.saveError.set(err instanceof Error ? err.message : 'Could not save the session.');
    }
  }

  /** Store the session together with its feedback and any translations made so far. */
  private async persist(): Promise<void> {
    const session = this.session();
    if (!session) return;
    const config = this.state.config();
    this.history.set(await this.bridge.saveSession({
      ...session,
      feedback: this.feedback() ?? undefined,
      feedbackSource: this.source(),
      translations: this.translations(),
      transcriptLanguage: session.transcriptLanguage ?? config?.transcriptLanguage,
      language: session.language ?? config?.language,
    }));
  }

  shownTranscript(): TranscriptEntry[] {
    const view = this.transcriptView();
    return (view !== 'original' && this.translations()[view]) || this.session()?.transcript || [];
  }

  async showTranscriptIn(view: 'original' | InterviewLanguage): Promise<void> {
    this.translateError.set('');
    const session = this.session();
    if (view === 'original' || this.translations()[view] || !session) {
      this.transcriptView.set(view);
      return;
    }
    this.translating.set(true);
    try {
      const result = await this.bridge.translateTranscript(session.transcript, view);
      this.translations.update((t) => ({ ...t, [view]: result.transcript }));
      this.transcriptView.set(view);
      if (this.saved()) await this.persist().catch(() => undefined); // keep the saved copy's translations current
    } catch (err) {
      this.translateError.set(`Could not translate the transcript (${err instanceof Error ? err.message : 'unknown error'}). Showing the original.`);
    } finally {
      this.translating.set(false);
    }
  }

  /** Talk this interview through with the Coach (the current one, or a saved one). */
  discuss(s?: SessionRecord): void {
    if (s) { this.coach.discussInterview(s, true); return; }
    const current = this.session();
    if (current) this.coach.discussInterview({ ...current, feedback: this.feedback() ?? undefined }, this.saved());
  }

  private scrollToOpen(): void {
    const id = this.openId();
    if (!id) return;
    setTimeout(() => document.getElementById(`hist-${id}`)?.scrollIntoView({ behavior: 'smooth', block: 'start' }));
  }

  private async loadHistory(): Promise<void> {
    try {
      this.history.set(await this.bridge.listSessions());
    } catch {
      this.historyError.set('Could not load your saved interviews.');
    }
  }

  async remove(id: string): Promise<void> {
    this.pendingRemove.set(null);
    try {
      this.history.set(await this.bridge.removeSession(id));
    } catch (err) {
      this.historyError.set(`Could not remove that interview (${err instanceof Error ? err.message : 'unknown error'}).`);
    }
  }

  /** Saved transcript in the language chosen for that interview, if it was translated. */
  savedTranscript(s: SessionRecord): TranscriptEntry[] {
    return (s.transcriptLanguage && s.translations?.[s.transcriptLanguage]) || s.transcript;
  }

  overall(fb: Feedback | null | undefined = this.feedback()): number {
    const scores = fb?.scores ?? [];
    return scores.length ? Math.round(scores.reduce((sum, s) => sum + s.score, 0) / scores.length) : 0;
  }

  get userAnswers(): number {
    return this.session()?.transcript.filter((t) => t.speaker === 'user').length ?? 0;
  }
}
